#!/usr/bin/env bash
# Builds catalog/kobento/json2rc.mjs: Kobento's JSON -> .rc converter (kobento-tools' json2rc,
# Apache-2.0) as one browser ES module, so an editor compiles an expanded Kobento design itself.
# The source and the bundler are pinned; bump KOBENTO_TOOLS_COMMIT to take a newer converter.
set -euo pipefail
KOBENTO_TOOLS_COMMIT="${KOBENTO_TOOLS_COMMIT:-7929c3c43a738fceffc00c8119de6bd7b1d856e0}"
ESBUILD_VERSION="0.24.0"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
git -C "$WORK" init -q tools
git -C "$WORK/tools" fetch -q --depth 1 https://github.com/kobento/kobento-tools.git "$KOBENTO_TOOLS_COMMIT"
git -C "$WORK/tools" checkout -q FETCH_HEAD
(cd "$WORK" && npm init -y >/dev/null && npm install --silent --no-audit --no-fund "esbuild@$ESBUILD_VERSION")
"$WORK/node_modules/.bin/esbuild" "$WORK/tools/json2rc/src/web.ts" --bundle --format=esm --minify \
  --target=es2020 --legal-comments=none \
  --banner:js="/* json2rc from kobento/kobento-tools@$KOBENTO_TOOLS_COMMIT, Apache-2.0 (see NOTICE). Generated by generator/build-json2rc.sh; do not edit. */" \
  --outfile="$HERE/catalog/kobento/json2rc.mjs"
echo "built catalog/kobento/json2rc.mjs from kobento-tools@$KOBENTO_TOOLS_COMMIT"
