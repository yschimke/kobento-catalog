#!/usr/bin/env python3
"""Snapshot Kobento's component library and generate a UI Builder catalog from it.

Kobento's components live in its MCP server, so the only machine-readable listing is the server's
own answers. This script turns them into committed files:

  catalog/components.snapshot.json   the interface facts only (names, params, slots, sets)
  catalog/ui-builder.json            a published `ui-builder.json` serving every component as a builtin
  catalog/kobento/definitions.json   each component's definition (params, slots, locals, body), so
                                     an editor can expand a call locally instead of asking Kobento
  catalog/kobento/theme.json         the default theme the definitions read: numbers, colours, modes

Kobento is open source under the Apache License 2.0 (https://github.com/kobento); the two files
under catalog/kobento/ are derived from it, see catalog/kobento/NOTICE.

Usage:

  snapshot.py fetch     # needs a Kobento token (see below); rewrites both files
  snapshot.py generate  # snapshot -> published file, offline
  snapshot.py check     # fails if the published file is not what `generate` writes

A token comes from https://mcp.kobento.dev/ (free account). Locally, put it in KOBENTO_TOKEN; in a
cloud session whose proxy injects the credential, leave KOBENTO_TOKEN unset.

See yschimke/compose-ui-builder's docs/design/UI_BUILDER_KOBENTO.md for why the snapshot keeps only interface facts and why the
catalog is all builtins.
"""

import json
import os
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "catalog" / "components.snapshot.json"
PUBLISHED = ROOT / "catalog" / "ui-builder.json"
DESIGNS = ROOT / "catalog" / "designs"
DEFINITIONS = ROOT / "catalog" / "kobento" / "definitions.json"
THEME = ROOT / "catalog" / "kobento" / "theme.json"
COMPILER = ROOT / "catalog" / "kobento" / "json2rc.mjs"
# The paths, on the delivery branch, of what an editor compiles a design with locally.
LOCAL_COMPILE_FILES = ["kobento/definitions.json", "kobento/theme.json", "kobento/json2rc.mjs"]

# The seed a new design starts from when none is named: a host opens the first template listed.
DEFAULT_TEMPLATE = "kobento-screen"
ENDPOINT = "https://mcp.kobento.dev/mcp"

PREFIX = "kobento/"

# Kobento param type -> the jsonType a design value is checked against. `action` params are not
# properties: a design states clicks as eventBindings, which the exporter writes as `onClick`.
JSON_TYPES = {
    "float": "number",
    "string": "string",
    "text": "string",
    # Kobento reads a bool as true/false or an exact 0/1, so either kind of state binds.
    "bool": ["boolean", "number"],
    "color": "string",
    "enum": "string",
    "list": "array",
    # A variable the component reads and writes itself (Switch.checked): a 0/1 or a number.
    "variable": ["boolean", "number"],
}

LOOKS = ["light", "dark", "mono-dark", "mono-light"]


def kebab(name: str) -> str:
    """`ActivityRings` -> `activity-rings`, `Chart3D` -> `chart3-d`; inverted by [pascal]."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "-", name).lower()


def pascal(component_id: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in component_id.split("-"))


def display_name(name: str) -> str:
    return re.sub(r"(?<=[a-z])(?=[A-Z0-9])", " ", name)


def call(tool: str, arguments: dict) -> dict:
    """One MCP `tools/call`, answered as the JSON its text content holds."""
    text = raw_call(tool, arguments)
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        sys.exit(f"{tool}: Kobento answered {text[:300]}")


def fetch() -> dict:
    return call("find", {"kind": "components", "interface": True, "limit": 1000})


# What a definition keeps: its structure, for an expander. Not its summary, docs, pitfalls or
# example call, which are Kobento's documentation rather than the component.
DEFINITION_KEYS = ("version", "params", "slots", "locals", "body")
PARAM_KEYS = ("type", "required", "default", "static", "values", "initial", "directional")


def definition_of(name: str) -> dict:
    found = call("get", {"name": name, "definition": True})["definition"]
    if found.get("component", name) != name:
        sys.exit(f"{name}: Kobento answered the definition of {found.get('component')}")
    definition = {key: found[key] for key in DEFINITION_KEYS if key in found}
    definition["params"] = {
        param: {key: spec[key] for key in PARAM_KEYS if key in spec}
        for param, spec in found.get("params", {}).items()
    }
    if "slots" in found:
        definition["slots"] = {
            slot: {"optional": spec.get("optional", True)} for slot, spec in found["slots"].items()
        }
    return definition


def definitions_of(snapshot: dict) -> dict:
    return {
        "$comment": (
            "GENERATED by generator/snapshot.py fetch from Kobento's MCP `get {name, definition: "
            "true}`. Derived from Kobento (Apache-2.0); see NOTICE. Regenerate, do not edit."
        ),
        "source": ENDPOINT,
        "license": "Apache-2.0",
        "components": {c["name"]: definition_of(c["name"]) for c in snapshot["components"]},
    }


def theme_tokens(definitions: dict) -> tuple:
    """Every `@theme.<number>` and `@colors.<name>` the definitions read."""
    text = json.dumps(definitions["components"])
    numbers = sorted(set(re.findall(r"@theme\.([A-Za-z0-9_]+)", text)))
    colors = sorted(set(re.findall(r"@colors\.([A-Za-z0-9_]+)", text)))
    return numbers, colors


def theme_of(definitions: dict) -> dict:
    """
    The default theme, read back from Kobento's own expansion: a probe component lays each theme
    number out as a width and paints each theme colour, and is expanded in every look. A token a
    component defines for itself (not the theme's) is reported missing and left out.
    """
    numbers, colors = theme_tokens(definitions)
    looks = {}
    for look in ("auto", "mono-dark", "mono-light"):
        while True:
            children = [
                {"text": {"value": n, "modifiers": [{"width": f"@theme.{n}"}]}} for n in numbers
            ] + [
                {"box": {"modifiers": [{"size": 1}, {"background": f"@colors.{c}"}]}}
                for c in colors
            ]
            probe = {
                "header": {"apiLevel": 7, "width": 100, "height": 100, "profiles": 513},
                "components": {
                    "ThemeProbe": {
                        "params": {},
                        "body": {"column": {"children": children}},
                        "call": {"ThemeProbe": {}},
                    }
                },
                "root": {"ThemeProbe": {}},
            }
            text = raw_call("convert", {"json": probe, "expanded": True, "theme": look})
            missing = re.search(r"theme (colour|number) '(\w+)' is not in the theme", text)
            if not missing:
                break
            (colors if missing.group(1) == "colour" else numbers).remove(missing.group(2))
        expanded = json.loads(text)["json"]
        laid = expanded["root"]["column"]["children"]
        looks[look] = {
            "numbers": {k["text"]["value"]: k["text"]["modifiers"][0]["width"] for k in laid if "text" in k},
            "colors": expanded.get("resources", {}).get("colors", {}),
        }
    auto = looks["auto"]
    return {
        "$comment": (
            "GENERATED by generator/snapshot.py fetch: Kobento's default theme, read back from its "
            "own expansion of a probe. Derived from Kobento (Apache-2.0); see NOTICE."
        ),
        "source": ENDPOINT,
        "license": "Apache-2.0",
        "numbers": auto["numbers"],
        "colors": auto["colors"],
        "modes": {
            look: {
                "numbers": {
                    k: v for k, v in looks[look]["numbers"].items() if auto["numbers"].get(k) != v
                },
                "colors": looks[look]["colors"],
            }
            for look in ("mono-dark", "mono-light")
        },
    }


def raw_call(tool: str, arguments: dict) -> str:
    """A `tools/call`'s text as is, so an error the caller recovers from is not fatal."""
    body = json.dumps(
        {
            "jsonrpc": "2.0",
            "id": 1,
            "method": "tools/call",
            "params": {"name": tool, "arguments": arguments},
        }
    ).encode()
    headers = {
        "content-type": "application/json",
        "accept": "application/json, text/event-stream",
    }
    token = os.environ.get("KOBENTO_TOKEN")
    if token:
        headers["authorization"] = f"Bearer {token}"
    request = urllib.request.Request(ENDPOINT, data=body, headers=headers, method="POST")
    with urllib.request.urlopen(request, timeout=120) as response:
        answer = json.loads(response.read())
    if "error" in answer:
        sys.exit(f"Kobento answered an error: {answer['error']}")
    return answer["result"]["content"][0]["text"]


def snapshot_of(found: dict) -> dict:
    """Interface facts only: no summaries or docs, which are Kobento's prose, not a contract."""
    components = []
    for component in sorted(found["components"], key=lambda c: c["name"]):
        name = component["name"]
        if pascal(kebab(name)) != name:
            sys.exit(f"{name}: does not survive the id round trip ({kebab(name)})")
        params = {}
        for param, spec in component.get("params", {}).items():
            params[param] = {
                key: spec[key]
                for key in ("type", "required", "default", "static", "values")
                if key in spec
            }
        slots = {slot: {"optional": spec.get("optional", True)}
                 for slot, spec in component.get("slots", {}).items()}
        components.append({"name": name, "params": params, "slots": slots})
    if len(components) != found.get("total", len(components)):
        sys.exit(f"find answered {len(components)} of {found.get('total')} components")
    return {
        "$comment": (
            "GENERATED by generator/snapshot.py fetch from Kobento's MCP "
            "`find {kind: components, interface: true}`. Interface facts only. Regenerate, do "
            "not edit; see yschimke/compose-ui-builder docs/design/UI_BUILDER_KOBENTO.md."
        ),
        "source": ENDPOINT,
        "sets": [s["name"] for s in found.get("sets", [])],
        "components": components,
    }


def notes(spec: dict) -> str:
    parts = [f"Kobento type {spec['type']}"]
    if "default" in spec:
        parts.append(f"default {json.dumps(spec['default'])}")
    if spec.get("static"):
        parts.append("static: fixed when the call is expanded, not bindable to state")
    elif spec["type"] in ("float", "bool", "color", "string"):
        parts.append('a literal or a "@variable"')
    return "; ".join(parts)


def property_of(name: str, spec: dict) -> dict:
    prop = {"name": name, "jsonType": JSON_TYPES[spec["type"]]}
    if spec.get("required"):
        prop["required"] = True
    if spec.get("values"):
        prop["allowedValues"] = spec["values"]
    prop["notes"] = notes(spec)
    return prop


def published_of(snapshot: dict) -> dict:
    builtins = {
        # The document itself: Kobento's root column on the theme background.
        PREFIX + "document": {
            "role": "screen-root",
            "displayName": "Kobento document",
            "canvas": "placeholder",
            "slots": {"content": {"ordered": True}},
        },
        # The format's own text primitive, not a library component.
        PREFIX + "text": {
            "role": "element",
            "displayName": "Text",
            "canvas": "placeholder",
            "properties": [
                {"name": "value", "jsonType": "string", "required": True,
                 "notes": 'the text, or a "@variable"'},
                {"name": "fontSize", "jsonType": "number", "notes": "sp"},
                {"name": "color", "jsonType": "string",
                 "notes": '"#AARRGGBB" or a theme token such as "@colors.onSurface"'},
            ],
        },
    }
    menu = {PREFIX + "text": {"group": "Text"}}
    for component in snapshot["components"]:
        name = component["name"]
        component_id = PREFIX + kebab(name)
        params = component["params"]
        builtin = {
            "role": "element",
            "displayName": display_name(name),
            "canvas": "placeholder",
            "properties": [
                property_of(param, spec)
                for param, spec in params.items()
                if spec["type"] != "action"
            ],
        }
        if component["slots"]:
            builtin["slots"] = {
                slot: {"required": not spec["optional"], "ordered": True}
                for slot, spec in component["slots"].items()
            }
        builtins[component_id] = builtin
        menu[component_id] = {"group": "Components"}
    templates = templates_of(builtins)
    clickable = sorted(
        PREFIX + kebab(c["name"])
        for c in snapshot["components"]
        if c["params"].get("onClick", {}).get("type") == "action"
    )
    return {
        "$comment": (
            "GENERATED by generator/snapshot.py generate from "
            "catalog/components.snapshot.json. Every component is a builtin: Kobento components "
            "have no Kotlin call site, so there is no record. See yschimke/compose-ui-builder docs/design/UI_BUILDER_KOBENTO.md."
        ),
        "schema": "compose-ui-builder-catalog/v1",
        "catalog": {
            "id": "kobento",
            "title": "Kobento components",
            "platform": "remote-compose",
            "platformLabel": "Kobento",
        },
        "statusSemantics": {
            "platform": "remote-compose",
            "platformLabel": "Kobento",
            "componentIdPrefix": PREFIX,
            "previewSurfaces": {
                "wasm": {
                    "fidelity": "approximate",
                    "reason": (
                        "Kobento components are expanded by Kobento's server, not composed. The "
                        "canvas draws each as a labelled placeholder; the picture comes from "
                        "playing the converted .rc."
                    ),
                },
            },
            "frame": {"adapter": "frame/rect"},
            # Seed documents, published beside this file at these paths (publish.yml).
            "templates": templates,
            "componentMenu": {"groupOrder": ["Text", "Components"], "components": menu},
            "builtins": builtins,
            # The document format a design exports as: compose-ui-builder's CatalogDocumentFormats
            # resolves this to its Kobento component JSON writer, which reads `kobento` below as
            # its policy (docs/design/UI_BUILDER_CATALOG_FORMATS.md there).
            "documentFormat": {"adapter": "kobento-component-json", "version": 1},
            # Read by the Kobento exporter, passed through verbatim by every other reader.
            # Files a host fetches from this catalog and serves to its editor, beside the
            # templates: what an editor compiles a Kobento design with, in the browser.
            "files": LOCAL_COMPILE_FILES,
            "kobento": {
                # How an editor compiles a design itself: expand its calls with the definitions and
                # theme (compose-ui-builder's KobentoComponentExpander), then json2rc. A host that
                # does not serve the files leaves the editor on its own export.
                "localCompile": {
                    "definitions": "kobento/definitions.json",
                    "theme": "kobento/theme.json",
                    "compiler": "kobento/json2rc.mjs",
                },
                "componentSets": snapshot["sets"],
                "looks": LOOKS,
                "clickable": clickable,
                # Params fixed when a call is expanded: the exporter refuses state bound to them.
                "staticParams": {
                    PREFIX + kebab(c["name"]): sorted(
                        p for p, spec in c["params"].items() if spec.get("static")
                    )
                    for c in snapshot["components"]
                    if any(spec.get("static") for spec in c["params"].values())
                },
            },
        },
    }


def templates_of(builtins: dict) -> list:
    """The seed documents in catalog/designs, default first, checked against this catalog.

    A host refuses the whole template set when one is unusable, and a seed naming a component the
    catalog does not serve opens as a broken design, so both are caught here rather than there.
    """
    paths = sorted(DESIGNS.glob("*.json"), key=lambda p: (p.stem != DEFAULT_TEMPLATE, p.stem))
    if not any(p.stem == DEFAULT_TEMPLATE for p in paths):
        sys.exit(f"catalog/designs has no {DEFAULT_TEMPLATE}.json, the default seed")
    for path in paths:
        where = path.relative_to(ROOT)
        design = json.loads(path.read_text())
        if design.get("id") != path.stem or design.get("template") != path.stem:
            sys.exit(f"{where}: id and template must both be {path.stem!r}")
        if design.get("catalogPin", {}).get("systemId") != "kobento":
            sys.exit(f"{where}: must be pinned to the kobento catalog")
        nodes = design.get("nodes", {})
        if not design.get("roots") or any(r not in nodes for r in design["roots"]):
            sys.exit(f"{where}: a root it does not hold")
        for node_id, node in nodes.items():
            component = node.get("componentId", "")
            # layout/* is the builder's own vocabulary, served beside every catalog.
            if component not in builtins and not component.startswith("layout/"):
                sys.exit(f"{where}: node {node_id} names {component}, which this catalog lacks")
            for children in node.get("slots", {}).values():
                missing = [c for c in children if c not in nodes]
                if missing:
                    sys.exit(f"{where}: node {node_id} slots name missing nodes {missing}")
    return [f"ui-builder/designs/{p.name}" for p in paths]


def write(path: Path, value: dict) -> None:
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")


def check_definitions(snapshot: dict) -> None:
    """The definitions and theme parse, and name exactly the snapshot's components."""
    definitions = json.loads(DEFINITIONS.read_text())
    theme = json.loads(THEME.read_text())
    names = {c["name"] for c in snapshot["components"]}
    if set(definitions["components"]) != names:
        sys.exit(
            f"{DEFINITIONS.relative_to(ROOT)} does not match the snapshot: run "
            f"{Path(__file__).name} fetch"
        )
    for name, definition in definitions["components"].items():
        if "body" not in definition:
            sys.exit(f"{DEFINITIONS.relative_to(ROOT)}: {name} has no body")
    if not COMPILER.read_text().startswith("/* json2rc from kobento/kobento-tools@"):
        sys.exit(f"{COMPILER.relative_to(ROOT)} is not generator/build-json2rc.sh's output")
    numbers, colors = theme_tokens(definitions)
    unknown = [n for n in numbers if n not in theme["numbers"]]
    if unknown:
        sys.exit(f"{THEME.relative_to(ROOT)} has no number for {', '.join(unknown)}")


def main() -> None:
    command = sys.argv[1] if len(sys.argv) > 1 else "check"
    if command == "fetch":
        snapshot = snapshot_of(fetch())
        write(SNAPSHOT, snapshot)
        definitions = definitions_of(snapshot)
        DEFINITIONS.parent.mkdir(parents=True, exist_ok=True)
        write(DEFINITIONS, definitions)
        write(THEME, theme_of(definitions))
        command = "generate"
    snapshot = json.loads(SNAPSHOT.read_text())
    if command == "generate":
        write(PUBLISHED, published_of(snapshot))
    elif command == "check":
        expected = json.dumps(published_of(snapshot), indent=2, ensure_ascii=False) + "\n"
        if PUBLISHED.read_text() != expected:
            sys.exit(f"{PUBLISHED.relative_to(ROOT)} is stale: run {Path(__file__).name} generate")
        check_definitions(snapshot)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
